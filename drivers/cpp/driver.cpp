// Crucible C++ driver — shared body for BOTH C++ corelibs:
//   cpp    -> corelib-cpp        (pure C++20, header-only)
//   c-cpp  -> corelib-c-cpp      (the C++ wrapper over the C corelib)
//
// build.sh selects which `sofab/sofab.hpp` is on the include path; the generated
// probe.hpp and the sofab:: API (IStreamInto, Result, Error) are the same across
// both except where CRUCIBLE_CORELIB_CPP says otherwise, so this one source builds
// against either.
//
// Decode goes through the GENERATED entry, exactly as an application calls it:
// message::Probe::try_decode returns the Result (the verdict) and fills the value in one
// call — in every profile and in limit mode alike, whatever the generated body does
// inside. The only exception is the chunked axes (SOFAB_SPLIT / SOFAB_CHUNK /
// SOFAB_CHUNK_SCRUB), see decode_streamed.
//
// Emits the canonical form (oracle/canonical.md) over the replay protocol
// (drivers/common/CONTRACT.md).
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <memory>
#include <optional>
#include <span>
#include <string>
#include <utility>
#include <vector>

#include "probe.hpp" // generated; pulls the variant's sofab/sofab.hpp

// Materialized-value walker (oracle/materialized.md), SOFAB_MATERIALIZE=1. GENERATED
// at build time from the schema descriptor by materialize_gen.py (build.sh runs it
// before this compile); a schema change regenerates it with zero hand-editing. It
// provides `std::string materialize(const message::Probe&)`, unrolled straight-line
// member-access code written against ONLY the member API shared by both corelib
// variants (std::string/std::vector/std::array vs FixedString/FixedBytes/InlineVector),
// so this one source stays variant-agnostic. See materialize_gen.py.
#include "materialize_gen.inc" // generated by build.sh -> gen/$VARIANT/

// CRUCIBLE_CORELIB_CPP (set by build.sh for cpp / cpp-fixed) marks the pure-C++
// corelib. The two corelibs' public APIs genuinely differ in two places this driver
// touches, and the macro selects between them:
//   - corelib-cpp's IStreamInto takes the receiver's field-span budget
//     (CORELIB_PLAN §6.2.1) as a constructor argument with no default (corelib-cpp#128);
//     the c-cpp wrapper's takes none. Only the hand-driven chunked stream needs it.
//   - corelib-cpp's sofab::Error carries LimitExceeded (the `L` verdict); the c-cpp
//     wrapper's does not.
//
// The budget the chunked stream states must be the SAME one the generated `try_decode`
// states, or the chunked path would decode under a different policy than the one-shot
// path and the chunk-invariance gate would report the difference as a divergence. The
// generated header defines SOFAB_MAX_DYN_BUFFERED_FIELD only when the build configured
// receiver caps (limit mode); without them the generated code passes SIZE_MAX literally.
#ifdef CRUCIBLE_CORELIB_CPP
#ifdef SOFAB_MAX_DYN_BUFFERED_FIELD
static const sofab::Limits kReceiverLimits{SOFAB_MAX_DYN_BUFFERED_FIELD};
#else
static const sofab::Limits kReceiverLimits{SIZE_MAX};
#endif
#endif

// One Error -> class mapping, used by BOTH verdicts that carry a class: the decode's
// `R` and the re-encode's `E`. It is one taxonomy (CORELIB_PLAN §6.3); which half of
// the stack produced the code is what the verdict letter says, not the class.
static const char *reject_class(sofab::Error e)
{
    switch (e)
    {
        case sofab::Error::InvalidMessage:  return "invalid_msg";
        case sofab::Error::InvalidArgument: return "argument";
        // Error::UsageError was removed in corelib-cpp#54; the canonical "usage"
        // class stays in oracle/canonical.md for the corelibs that still have it.
        // Anything unmapped falls through to "other".
        case sofab::Error::BufferFull:      return "buffer_full";
        default:                            return "other";
    }
}

// ---- the streaming axes (drivers/common/CONTRACT.md, "The streaming axes") ------
//
// The replay protocol hands each record over whole and re-encodes it with one call, so
// the generated API's streaming surfaces are unreachable through it. Five environment
// variables open them; unset, every one of them is today's behaviour byte for byte.
//
// C++ is the one backend with **no generated `decoder()`** (crucible#132): chunked
// decode is driven by hand (decode_streamed). With none of the chunked axes set the
// driver calls the generated try_decode and never builds a stream itself.
struct StreamCfg
{
    long split = 0;                            // SOFAB_SPLIT=k  — two chunks at k
    long chunk = 0;                            // SOFAB_CHUNK=n  — fixed-size chunks
    bool scrub = false;                        // SOFAB_CHUNK_SCRUB=1
    enum Enc { EncNew, EncTo, EncStream } enc = EncNew;  // SOFAB_ENCODE
    long flush = 0;                            // SOFAB_FLUSH=n  — OStream buffer size
    long fail = 0;                             // SOFAB_ENCODE_FAIL=n — destination cap
};

static StreamCfg g_cfg;

static long env_long(const char *name)
{
    const char *v = std::getenv(name);
    if (!v || !*v) return 0;
    return std::strtol(v, nullptr, 10);
}

// Read once at startup. An unknown SOFAB_ENCODE value is a hard error rather than a
// fallback: reporting a mode as passing that never ran is the one failure the encode
// gate exists to prevent, so the driver must never quietly substitute another surface.
static void read_stream_cfg()
{
    g_cfg.split = env_long("SOFAB_SPLIT");
    g_cfg.chunk = env_long("SOFAB_CHUNK");
    g_cfg.flush = env_long("SOFAB_FLUSH");
    g_cfg.fail = env_long("SOFAB_ENCODE_FAIL");
    const char *s = std::getenv("SOFAB_CHUNK_SCRUB");
    g_cfg.scrub = s && *s && std::strcmp(s, "0") != 0;
    const char *e = std::getenv("SOFAB_ENCODE");
    if (!e || !*e || std::strcmp(e, "new") == 0)       g_cfg.enc = StreamCfg::EncNew;
    else if (std::strcmp(e, "to") == 0)                g_cfg.enc = StreamCfg::EncTo;
    else if (std::strcmp(e, "stream") == 0)            g_cfg.enc = StreamCfg::EncStream;
    else
    {
        std::fprintf(stderr, "crucible-cpp: unknown SOFAB_ENCODE=%s "
                             "(this backend has new, to, stream)\n", e);
        std::exit(2);
    }

    // Announce the configuration on stderr (never parsed — CONTRACT.md). Without this
    // a driver that silently ignored the variables would be indistinguishable from one
    // that honours them: identical stdout either way. That is the vacuous pass the
    // opt-in roster guards against at the gate level; this is the same guard at the
    // driver level, and it is what makes "this driver really re-feeds" checkable
    // rather than asserted.
    if (g_cfg.split || g_cfg.chunk || g_cfg.scrub || g_cfg.flush ||
        g_cfg.enc != StreamCfg::EncNew || g_cfg.fail)
    {
        std::fprintf(stderr,
                     "crucible-cpp: streaming cfg split=%ld chunk=%ld scrub=%d "
                     "enc=%s flush=%ld fail=%ld\n",
                     g_cfg.split, g_cfg.chunk, g_cfg.scrub ? 1 : 0,
                     g_cfg.enc == StreamCfg::EncNew ? "new"
                         : g_cfg.enc == StreamCfg::EncTo ? "to" : "stream",
                     g_cfg.flush, g_cfg.fail);
    }

}

static bool chunked() { return g_cfg.split > 0 || g_cfg.chunk > 0 || g_cfg.scrub; }

// SOFAB_REUSE=1 (CONTRACT.md, "Reused destination"): every record decodes into ONE
// destination held for the whole run. The generated try_decode resets it first and
// keeps the buffers reset() keeps, so each line must equal the fresh-destination one.
static message::Probe *g_reused = nullptr;

static void read_reuse_cfg()
{
    const char *s = std::getenv("SOFAB_REUSE");
    if (s && *s && std::strcmp(s, "0") != 0)
    {
        g_reused = new message::Probe();
        std::fputs("crucible-cpp: reuse=1\n", stderr);
    }
}

// How the record is cut on its way into the decoder. Never an empty chunk for a
// non-empty record: k<=0, k>=len and n>=len all mean one chunk holding the whole
// record. A zero-length record is ONE empty chunk, fed once like any other record
// (CONTRACT.md) — the driver never answers the empty message itself.
static std::vector<std::pair<std::size_t, std::size_t>> slices(std::size_t len)
{
    std::vector<std::pair<std::size_t, std::size_t>> out;
    if (g_cfg.chunk > 0 && len > 0)
    {
        std::size_t n = static_cast<std::size_t>(g_cfg.chunk);
        for (std::size_t o = 0; o < len; o += n)
            out.emplace_back(o, std::min(n, len - o));
        return out;
    }
    if (g_cfg.split > 0 && static_cast<std::size_t>(g_cfg.split) < len)
    {
        std::size_t k = static_cast<std::size_t>(g_cfg.split);
        out.emplace_back(0, k);
        out.emplace_back(k, len - k);
        return out;
    }
    out.emplace_back(0, len);
    return out;
}

// Feed `data` in the configured pieces through ONE stream. This is the ONE place the
// driver drives a stream itself, and only because the C++ generator emits no chunked
// `decoder()` (crucible#132) — try_decode takes the whole record in one call, so the
// chunked axes cannot be reached through it. The stream is built exactly the way THIS
// profile's generated try_decode builds it (gen/<variant>/probe.hpp), so the pieces are
// the only difference and a chunk-invariance failure cannot be a construction difference:
// reset the destination and decode into it through an IStreamInto<Probe> — on
// corelib-cpp with the generated receiver budget, which that constructor requires
// (generator#749 made both profiles emit this one shape).
// The verdict is the last feed's Result — C++ has no `finish()`, so this Result *is* the
// status the contract requires the verdict to come from. An error that is not
// `incomplete` is terminal and stops the feeding, per the contract.
//
// SOFAB_CHUNK_SCRUB copies each piece into a buffer the driver owns, feeds that, and
// overwrites it with 0xA5 once `feed` returns. A decoder that borrowed from the chunk
// rather than copying out of it then reads back the scrub pattern.
static sofab::IStreamImpl::Result decode_streamed(const std::uint8_t *data,
                                                  std::size_t len,
                                                  message::Probe &m)
{
    m.reset();
#ifdef CRUCIBLE_CORELIB_CPP
    sofab::IStreamInto<message::Probe> is{m, kReceiverLimits};
#else
    sofab::IStreamInto<message::Probe> is{m};
#endif

    // Result has no public constructor in either corelib, so the verdict is held in an
    // optional until the first feed; slices() always yields at least one piece (an
    // empty record is one empty piece), so it is always set by the time it is read.
    std::vector<std::uint8_t> scratch;
    std::optional<sofab::IStreamImpl::Result> r;
    for (auto [off, n] : slices(len))
    {
        if (g_cfg.scrub)
        {
            scratch.assign(data + off, data + off + n);
            r.emplace(is.feed(scratch.data(), n));
            if (n) std::memset(scratch.data(), 0xA5, n);
        }
        else
        {
            r.emplace(is.feed(data + off, n));
        }
        if (!r->ok() && !r->incomplete()) break;   // INVALID is terminal
    }
    return *r;
}

// The outcome of one re-encode: the bytes, or the refusal with its code.
//
// generator#656 made a refusal reachable from an ordinary setter, and until
// generator#736 (fixed 2026-10-12) the generated C++ entry points could not report one:
// `encode()` answered with an empty vector and `encodeTo()` with 0, which is also what
// the all-default message produces, whose encoding is legitimately zero bytes (§2). This
// driver worked around it by re-running `serialize()` on a stream of its own whenever the
// surface came back empty, and reading the stream's latched error. **That is gone.** Both
// entry points now return `sofab::Error` and are `[[nodiscard]]`, as Rust's did after
// generator#673 — so the status comes from the call that was made, and the workaround
// would only be a second opinion about it.
struct EncodeOutcome
{
    std::vector<std::uint8_t> bytes;
    bool refused = false;
    sofab::Error code = sofab::Error::None;
};

// Which generated call produces the `A <hex>` payload. All three must emit identical
// bytes for one decoded value — the family is byte-canonical — and SOFAB_FLUSH must not
// change that either: it hands the OStream an n-byte buffer, so the sink receives the
// message in n-byte pieces and the encoder crosses a buffer boundary at every offset.
static EncodeOutcome encode_via(const message::Probe &m)
{
    EncodeOutcome r;
    // SOFAB_ENCODE_FAIL=n (CONTRACT.md): hand the encoder a destination of n bytes with
    // no sink behind it, so a message that does not fit is REFUSED (BufferFull) rather
    // than truncated and the `E` mapping runs for real. `encodeTo` IS that destination,
    // whichever surface SOFAB_ENCODE would otherwise have selected.
    if (g_cfg.fail > 0)
    {
        const std::size_t room =
            static_cast<std::size_t>(g_cfg.fail) < message::Probe::_maxSize
                ? static_cast<std::size_t>(g_cfg.fail) : message::Probe::_maxSize;
        std::vector<std::uint8_t> buf(room ? room : 1);
        std::size_t used = 0;
        sofab::Error code = m.encodeTo(buf.data(), room, used);
        if (code != sofab::Error::None) { r.refused = true; r.code = code; return r; }
        buf.resize(used);
        r.bytes = std::move(buf);
        return r;
    }
    if (g_cfg.enc == StreamCfg::EncStream)
    {
        // stream: serialize into an OStream, collecting what it flushes. The stream's
        // own latched status is the verdict here — NOT the Result `serialize` returns,
        // which carries only the last write's code because the generated body discards
        // the intermediate ones. Measured on a two-byte destination: `code()` answered
        // None while the stream was already not ok.
        std::size_t cap = g_cfg.flush > 0 ? static_cast<std::size_t>(g_cfg.flush)
                                          : message::Probe::_maxSize;
        if (cap == 0) cap = 1;
        std::shared_ptr<std::uint8_t[]> buf(new std::uint8_t[cap]);
        {
            sofab::OStream os{[&r](std::span<const std::uint8_t> s) {
                                  r.bytes.insert(r.bytes.end(), s.begin(), s.end());
                              },
                              buf, cap};
            (void)m.serialize(os);
            os.flush();   // hand over whatever is still buffered
            if (!os.ok()) { r.refused = true; r.code = os.error(); }
        }
        if (r.refused) r.bytes.clear();
        return r;
    }
    if (g_cfg.enc == StreamCfg::EncNew)
    {
        sofab::Error code = m.encode(r.bytes);
        if (code != sofab::Error::None) { r.refused = true; r.code = code; r.bytes.clear(); }
        return r;
    }
    std::vector<std::uint8_t> buf(message::Probe::_maxSize);
    std::size_t used = 0;
    sofab::Error code = m.encodeTo(buf.data(), buf.size(), used);
    if (code != sofab::Error::None) { r.refused = true; r.code = code; return r; }
    buf.resize(used);
    r.bytes = std::move(buf);
    return r;
}

static void decode_and_report(const std::uint8_t *data, std::size_t len, FILE *out)
{
    message::Probe fresh; // schema defaults
    message::Probe &m = g_reused ? *g_reused : fresh;

    // The generated try_decode, called the way an application calls it — in every
    // profile, in limit mode, and for the empty record alike. Only the chunked axes go
    // through the hand-driven stream (decode_streamed, crucible#132).
    auto r = chunked() ? decode_streamed(data, len, m)
                       : message::Probe::try_decode(data, len, m);
    if (r.incomplete())
    {
        // INCOMPLETE (MESSAGE_SPEC §7): bytes end mid-message — the third
        // canonical verdict, neither accept (A) nor reject (R). Not an error.
        std::fputs("I\n", out);
        return;
    }
    if (!r.ok())
    {
#ifdef CRUCIBLE_CORELIB_CPP
        // LIMIT_EXCEEDED (generator#102, limit mode only): a configured
        // receiver-side cap on a schema-unbounded field. A policy rejection
        // distinct from INVALID — its own verdict `L`, not `R`. Only the pure-C++
        // corelib's Error carries LimitExceeded (the c-cpp wrapper's does not).
        if (r.code() == sofab::Error::LimitExceeded)
        {
            std::fputs("L\n", out);
            return;
        }
#endif
        std::fprintf(out, "R %s\n", reject_class(r.code()));
        return;
    }

    // Accept. In materialize mode (oracle/materialized.md) dump the decoded value
    // field-by-field instead of re-encoding it to wire.
    static int materialize = -1;
    if (materialize < 0) materialize = std::getenv("SOFAB_MATERIALIZE") ? 1 : 0;
    if (materialize)
    {
        // GENERATED walker (materialize_gen.inc): dump the decoded value
        // field-by-field. Output is all ASCII (hex/digits/punctuation, no NUL), so
        // writing the std::string as a C string is safe.
        std::string dump = ::materialize(m);
        std::fputs("A ", out);
        std::fwrite(dump.data(), 1, dump.size(), out);
        std::fputc('\n', out);
        return;
    }

    // Accept: re-encode the decoded value and emit its canonical wire as hex, through
    // whichever encode surface SOFAB_ENCODE selects (default: the allocating encode()).
    EncodeOutcome enc = encode_via(m);
    if (enc.refused)
    {
        // The decode ACCEPTED and the re-encode of that value was REFUSED: its own
        // verdict (oracle/canonical.md "The fifth verdict `E`"), never a reject
        // class — the input was not malformed, this implementation just will not
        // write back what it read.
        std::fprintf(out, "E %s\n", reject_class(enc.code));
        return;
    }
    std::fputs("A ", out);
    for (std::uint8_t b : enc.bytes)
    {
        std::fprintf(out, "%02x", b);
    }
    std::fputc('\n', out);
}

int main()
{
    read_stream_cfg();
    read_reuse_cfg();
    std::vector<std::uint8_t> buf;
    for (;;)
    {
        std::uint8_t lenbytes[4];
        std::size_t got = std::fread(lenbytes, 1, 4, stdin);
        if (got == 0) break; // clean EOF at record boundary
        if (got != 4) { std::fprintf(stderr, "crucible-cpp: short length prefix\n"); return 1; }

        std::uint32_t n = (std::uint32_t)lenbytes[0] | ((std::uint32_t)lenbytes[1] << 8) |
                          ((std::uint32_t)lenbytes[2] << 16) | ((std::uint32_t)lenbytes[3] << 24);

        buf.resize(n);
        if (n > 0 && std::fread(buf.data(), 1, n, stdin) != n)
        {
            std::fprintf(stderr, "crucible-cpp: short payload\n");
            return 1;
        }

        decode_and_report(buf.data(), n, stdout);
        std::fflush(stdout);
    }
    return 0;
}
